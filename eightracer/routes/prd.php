<?php

use App\Http\Controllers\Api\AnalyticsController;
use App\Http\Controllers\Api\AssessmentController;
use App\Http\Controllers\Api\AttachmentController;
use App\Http\Controllers\Api\DashboardController;
use App\Http\Controllers\Api\GoogleAuthController;
use App\Http\Controllers\Api\MajorRecommendationController;
use App\Http\Controllers\Api\ProfileController;
use App\Http\Controllers\Api\ReferenceController;
use App\Http\Controllers\Api\SchoolAuthController;
use App\Http\Controllers\Api\SchoolEligibilityController;
use App\Http\Controllers\Api\StudentEconomyController;
use App\Http\Controllers\Api\StudentSupportController;
use App\Http\Controllers\Api\StudyTracerController;
use App\Http\Middleware\RequireStudent;
use Illuminate\Support\Facades\Route;

Route::get('/faq', [DashboardController::class, 'faq']);
Route::post('/register/verify', [SchoolAuthController::class, 'verifyRegistration'])->middleware('throttle:otp-verify');
Route::post('/forgot-password/verify', [SchoolAuthController::class, 'verifyReset'])->middleware('throttle:otp-verify');
Route::post('/auth/google/challenge', [GoogleAuthController::class, 'challenge'])->middleware('throttle:10,1');
Route::post('/auth/google', [GoogleAuthController::class, 'login'])->middleware('throttle:login');
Route::middleware(['auth:sanctum', 'token.lifetime', 'throttle:api'])->group(function () {
    Route::get('/beranda', [DashboardController::class, 'index']);
    Route::get('/profile', [ProfileController::class, 'show']);
    Route::patch('/profile', [ProfileController::class, 'update']);
    Route::post('/profile/password/otp', [ProfileController::class, 'passwordOtp'])->middleware('throttle:otp-request');
    Route::put('/profile/password', [ProfileController::class, 'password'])->middleware('throttle:otp-verify');
    Route::post('/profile/email/otp', [ProfileController::class, 'emailOtp'])->middleware('throttle:otp-request');
    Route::post('/profile/email/verify', [ProfileController::class, 'emailVerify'])->middleware('throttle:otp-verify');
    Route::post('/profile/photo', [ProfileController::class, 'photo'])->middleware('throttle:5,1');
    Route::get('/profile/photo', [ProfileController::class, 'photoRead']);
    Route::post('/profile/google', [GoogleAuthController::class, 'link'])->middleware('throttle:otp-verify');
    Route::get('/lampiran/{id}', [AttachmentController::class, 'download'])->whereNumber('id');
    Route::middleware(RequireStudent::class)->group(function () {
        Route::get('/asesmen/saya', [AssessmentController::class, 'mine']);
        Route::get('/eligibilitas/saya', [SchoolEligibilityController::class, 'mine']);
        Route::get('/rekomendasi-jurusan/saya', [MajorRecommendationController::class, 'mine']);
        Route::get('/jejak-alumni', [StudyTracerController::class, 'studentIndex']);
        Route::get('/jejak-alumni/{id}', [StudyTracerController::class, 'studentShow'])->whereNumber('id');
        Route::get('/pola-alumni', [AnalyticsController::class, 'published']);
    });
    Route::middleware('administrator')->group(function () {
        Route::get('/referensi/{type}', [ReferenceController::class, 'index']);
        Route::post('/referensi/{type}', [ReferenceController::class, 'store']);
        Route::put('/referensi/{type}/{id}', [ReferenceController::class, 'update'])->whereNumber('id');
        Route::delete('/referensi/{type}/{id}', [ReferenceController::class, 'destroy'])->whereNumber('id');
        Route::put('/siswa/{siswa}/ekonomi', [StudentEconomyController::class, 'save']);
        Route::match(['put', 'delete'], '/siswa/{siswa}/keluarga/{type}/{id}', [StudentEconomyController::class, 'updateRelated'])->whereNumber('id');
        Route::get('/siswa/{siswa}/data-pendukung', [StudentSupportController::class, 'show']);
        Route::put('/siswa/{siswa}/nilai-rapor', [StudentSupportController::class, 'grades']);
        Route::put('/siswa/{siswa}/presensi', [StudentSupportController::class, 'attendance']);
        Route::patch('/siswa/{siswa}/kelengkapan', [StudentSupportController::class, 'completeness']);
        Route::post('/siswa/{siswa}/kelas', [StudentSupportController::class, 'classroom']);
        Route::put('/siswa/{siswa}/minat', [StudentSupportController::class, 'interests']);
        Route::post('/siswa/{siswa}/pendukung/{type}', [StudentSupportController::class, 'record']);
        Route::put('/siswa/{siswa}/pendukung/{type}/{id}', [StudentSupportController::class, 'record'])->whereNumber('id');
        Route::delete('/siswa/{siswa}/pendukung/{type}/{id}', [StudentSupportController::class, 'destroy'])->whereNumber('id');
        Route::get('/siswa/{siswa}/asesmen', [AssessmentController::class, 'history']);
        Route::post('/siswa/{siswa}/asesmen', [AssessmentController::class, 'store']);
        Route::post('/siswa/{siswa}/lampiran', [AttachmentController::class, 'store'])->middleware('throttle:5,1');
        Route::get('/program-eligibilitas', [SchoolEligibilityController::class, 'index']);
        Route::post('/program-eligibilitas', [SchoolEligibilityController::class, 'save']);
        Route::put('/program-eligibilitas/{id}', [SchoolEligibilityController::class, 'save']);
        Route::delete('/program-eligibilitas/{id}', [SchoolEligibilityController::class, 'archive']);
        Route::post('/program-eligibilitas/{id}/hitung', [SchoolEligibilityController::class, 'calculate']);
        Route::get('/program-eligibilitas/{id}/hasil', [SchoolEligibilityController::class, 'results']);
        Route::get('/klaster-jurusan', [MajorRecommendationController::class, 'clusters']);
        Route::post('/klaster-jurusan', [MajorRecommendationController::class, 'saveCluster']);
        Route::put('/klaster-jurusan/{id}', [MajorRecommendationController::class, 'saveCluster']);
        Route::delete('/klaster-jurusan/{id}', [MajorRecommendationController::class, 'archive']);
        Route::get('/rekomendasi-jurusan', [MajorRecommendationController::class, 'index']);
        Route::post('/siswa/{siswa}/rekomendasi-jurusan/generate', [MajorRecommendationController::class, 'generate'])->middleware('throttle:5,1');
        Route::patch('/rekomendasi-jurusan/{batch}/review', [MajorRecommendationController::class, 'review']);
        Route::get('/study-tracer', [StudyTracerController::class, 'index']);
        Route::post('/study-tracer', [StudyTracerController::class, 'save']);
        Route::get('/study-tracer/{id}', [StudyTracerController::class, 'show']);
        Route::put('/study-tracer/{id}', [StudyTracerController::class, 'save']);
        Route::delete('/study-tracer/{id}', [StudyTracerController::class, 'destroy']);
        Route::patch('/study-tracer/{id}/publikasi', [StudyTracerController::class, 'publish']);
        Route::patch('/alumni-progress/{id}', [StudyTracerController::class, 'progress']);
        Route::patch('/alumni-progress/{id}/publikasi', [StudyTracerController::class, 'publishProgress']);
        Route::get('/analitik-beasiswa', [AnalyticsController::class, 'index']);
        Route::get('/analitik-beasiswa/export', [AnalyticsController::class, 'export']);
        Route::patch('/siswa/{siswa}/izin-analitik', [AnalyticsController::class, 'consent']);
        Route::get('/analitik-beasiswa/pola',[AnalyticsController::class, 'cohorts']);
        Route::post('/analitik-beasiswa/pola',[AnalyticsController::class, 'create']);
        Route::patch('/analitik-beasiswa/pola/{id}/publikasi',[AnalyticsController::class, 'publish']);
    });
});
